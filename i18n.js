export function resolveLanguage(preference = 'auto', languages = []) {
 const selected = Object.entries(languageNames).find(([,name])=>name===preference)?.[0] || preference;
 if (selected !== 'auto' && Object.hasOwn(messages,selected)) return selected;
 for (const candidate of languages) {
   const base = candidate.toLowerCase().split(/[-_]/)[0];
   if (Object.hasOwn(messages,base)) return base;
 }
 return 'en';
}
export function translate(language,key,values={}) {
 const entries=Object.hasOwn(messages,language)?messages[language]:messages.en;
 const template=Object.hasOwn(entries,key)?entries[key]:Object.hasOwn(messages.en,key)?messages.en[key]:key;
 return template.replace(/\{(\w+)\}/g, (match,name) => Object.hasOwn(values,name) ? String(values[name]) : match);
}
