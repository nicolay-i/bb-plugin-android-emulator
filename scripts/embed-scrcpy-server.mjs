// Regenerates host/scrcpy-server.ts from the official scrcpy release.
// The version must match the Tango options class used in host/session.ts.
import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

const VERSION = '3.3.3';
const SHA256 = '7e70323ba7f259649dd4acce97ac4fefbae8102b2c6d91e2e7be613fd5354be0';
const url = `https://github.com/Genymobile/scrcpy/releases/download/v${VERSION}/scrcpy-server-v${VERSION}`;

const response = await fetch(url);
if (!response.ok) throw new Error(`Download failed: HTTP ${response.status}`);
const bytes = Buffer.from(await response.arrayBuffer());
const actual = createHash('sha256').update(bytes).digest('hex');
if (actual !== SHA256) throw new Error(`SHA256 mismatch: ${actual}`);
await writeFile(new URL('../host/scrcpy-server.ts', import.meta.url), [
  `// Generated by scripts/embed-scrcpy-server.mjs. Do not edit.`,
  `// scrcpy-server v${VERSION}, Apache-2.0, https://github.com/Genymobile/scrcpy`,
  `export const SCRCPY_SERVER_VERSION = '${VERSION}';`,
  `export const SCRCPY_SERVER_SHA256 = '${SHA256}';`,
  `export const SCRCPY_SERVER_BASE64 = '${bytes.toString('base64')}';`,
  '',
].join('\n'));
console.log(`host/scrcpy-server.ts: ${bytes.length} bytes, sha256 ok`);
