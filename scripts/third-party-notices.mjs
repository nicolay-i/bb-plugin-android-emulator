// Writes THIRD_PARTY_NOTICES.md for everything bundled into dist/: production npm packages and scrcpy-server.
// Run after changing dependencies: node scripts/third-party-notices.mjs
import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/(\w:)/, '$1');
const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: root, encoding: 'utf8' }));
const names = new Set();
(function walk(deps = {}) {
  for (const [name, info] of Object.entries(deps)) {
    if (!info.version) continue; // uninstalled optional peers (ws -> bufferutil) are not bundled
    names.add(name);
    walk(info.dependencies);
  }
})(tree.dependencies);

const sections = [...names].sort().map(name => {
  const dir = join(root, 'node_modules', name);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find(entry => /^licen[cs]e(\.(md|txt))?$/i.test(entry));
  if (!file) throw new Error(`${name}: no license file`);
  return `## ${name} ${pkg.version} (${pkg.license})\n\n\`\`\`\n${readFileSync(join(dir, file), 'utf8').trim()}\n\`\`\``;
});

const { SCRCPY_SERVER_VERSION, SCRCPY_SERVER_SHA256 } = await import('../host/scrcpy-server.ts');
// @yume-chan/scrcpy ships the upstream scrcpy Apache-2.0 license text.
const apache = readFileSync(join(root, 'node_modules', '@yume-chan', 'scrcpy', 'scrcpy.LICENSE'), 'utf8').trim();
const scrcpy = `## scrcpy-server ${SCRCPY_SERVER_VERSION} (Apache-2.0)

Unmodified binary from https://github.com/Genymobile/scrcpy/releases/tag/v${SCRCPY_SERVER_VERSION},
embedded in host/scrcpy-server.ts and pushed to the Android device at runtime.
SHA-256: ${SCRCPY_SERVER_SHA256}

Copyright (C) 2018 Genymobile
Copyright (C) 2018-2025 Romain Vimont

\`\`\`
${apache}
\`\`\``;

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'),
  `# Third-party notices\n\nThe plugin bundles the following components. Generated by scripts/third-party-notices.mjs.\n\n${[scrcpy, ...sections].join('\n\n')}\n`);
console.log(`THIRD_PARTY_NOTICES.md: scrcpy-server + ${sections.length} npm packages`);
